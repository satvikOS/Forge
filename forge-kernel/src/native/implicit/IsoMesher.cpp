// ===========================================================================
// Mesh measurements
// ===========================================================================
double Mesh::volume() const {
    // Signed volume = (1/6) * sum over triangles of dot(v0, cross(v1, v2)).
    double v6 = 0.0;
    for (const auto& t : triangles) {
        const Vec3& a = positions[t[0]];
        const Vec3& b = positions[t[1]];
        const Vec3& c = positions[t[2]];
        // dot(a, cross(b, c))
        const double cx = b.y * c.z - b.z * c.y;
        const double cy = b.z * c.x - b.x * c.z;
        const double cz = b.x * c.y - b.y * c.x;
        v6 += a.x * cx + a.y * cy + a.z * cz;
    }
    return v6 / 6.0;
}

double Mesh::area() const {
    double total = 0.0;
    for (const auto& t : triangles) {
        const Vec3& a = positions[t[0]];
        const Vec3& b = positions[t[1]];
        const Vec3& c = positions[t[2]];
        const Vec3 ab = b - a;
        const Vec3 ac = c - a;
        const double cx = ab.y * ac.z - ab.z * ac.y;
        const double cy = ab.z * ac.x - ab.x * ac.z;
        const double cz = ab.x * ac.y - ab.y * ac.x;
        total += 0.5 * std::sqrt(cx * cx + cy * cy + cz * cz);
    }
    return total;
}

