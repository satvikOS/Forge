Mesh IsoMesher::march(const Sdf& sdf, const GridSpec& grid, double isovalue) {
    if (!sdf.valid()) throw std::runtime_error("IsoMesher::march: empty Sdf");
    if (grid.nx < 1 || grid.ny < 1 || grid.nz < 1)
        throw std::runtime_error("IsoMesher::march: grid must have >=1 cell per axis");

    Mesh mesh;

    const int Nx = grid.nx, Ny = grid.ny, Nz = grid.nz;
    const int VX = Nx + 1, VY = Ny + 1, VZ = Nz + 1;
    const double dx = (grid.max.x - grid.min.x) / Nx;
    const double dy = (grid.max.y - grid.min.y) / Ny;
    const double dz = (grid.max.z - grid.min.z) / Nz;

    // Pre-sample the field at every grid vertex (one eval per vertex, reused by
    // all 8 incident cells).
    std::vector<double> field(static_cast<size_t>(VX) * VY * VZ);
    auto vidx = [&](int i, int j, int k) {
        return (static_cast<size_t>(k) * VY + j) * VX + i;
    };
    auto vpos = [&](int i, int j, int k) {
        return Vec3{grid.min.x + i * dx, grid.min.y + j * dy, grid.min.z + k * dz};
    };
    for (int k = 0; k < VZ; ++k)
        for (int j = 0; j < VY; ++j)
            for (int i = 0; i < VX; ++i)
                field[vidx(i, j, k)] = sdf.eval(vpos(i, j, k)) - isovalue;

    // Vertex de-duplication: an edge is shared by up to 4 cells; key it by the
    // pair of grid-vertex linear indices so each surface vertex is emitted once.
    // This yields an indexed (shared-vertex) mesh suitable for volume/area.
    std::map<std::pair<size_t, size_t>, int> edgeVertex;

    auto interp = [&](int ci, int cj, int ck, int c0, int c1) -> int {
        // Corner grid indices of the two endpoints.
        const int i0 = ci + cornerOffset[c0][0];
        const int j0 = cj + cornerOffset[c0][1];
        const int k0 = ck + cornerOffset[c0][2];
        const int i1 = ci + cornerOffset[c1][0];
        const int j1 = cj + cornerOffset[c1][1];
        const int k1 = ck + cornerOffset[c1][2];
        size_t a = vidx(i0, j0, k0);
        size_t b = vidx(i1, j1, k1);
        auto key = a < b ? std::make_pair(a, b) : std::make_pair(b, a);
        auto it = edgeVertex.find(key);
        if (it != edgeVertex.end()) return it->second;

        const double fa = field[a];
        const double fb = field[b];
        // Linear root of f along the edge. Guard the degenerate fa==fb case.
        double t = 0.5;
        const double denom = fa - fb;
        if (std::fabs(denom) > 1e-300) t = fa / denom; // f=0 => fa + t*(fb-fa)=0
        t = t < 0.0 ? 0.0 : (t > 1.0 ? 1.0 : t);

        const Vec3 pa = vpos(i0, j0, k0);
        const Vec3 pb = vpos(i1, j1, k1);
        const Vec3 p = pa + (pb - pa) * t;

        int newIndex = static_cast<int>(mesh.positions.size());
        mesh.positions.push_back(p);
        edgeVertex.emplace(key, newIndex);
        return newIndex;
    };

    int edgeVerts[12];

    for (int k = 0; k < Nz; ++k) {
        for (int j = 0; j < Ny; ++j) {
            for (int i = 0; i < Nx; ++i) {
                // Build the 8-bit cube index. Bit c set when corner is INSIDE
                // (f < 0). This is the standard convention matching the tables.
                int cubeIndex = 0;
                double fc[8];
                for (int c = 0; c < 8; ++c) {
                    const int ic = i + cornerOffset[c][0];
                    const int jc = j + cornerOffset[c][1];
                    const int kc = k + cornerOffset[c][2];
                    fc[c] = field[vidx(ic, jc, kc)];
                    if (fc[c] < 0.0) cubeIndex |= (1 << c);
                }
                const int edges = edgeTable[cubeIndex];
                if (edges == 0) continue; // wholly inside or outside

                // Compute the surface vertex on each crossed edge.
                for (int e = 0; e < 12; ++e) {
                    if (edges & (1 << e)) {
                        edgeVerts[e] = interp(i, j, k, edgeCorner[e][0], edgeCorner[e][1]);
                    }
                }

                // Emit triangles for this case.
                //
                // ORIENTATION: with our cube-index convention (bit set when the
                // corner is INSIDE the solid, f < 0), the Lorensen-Cline
                // triTable winds each triangle so its normal points toward the
                // INSIDE. We want outward-facing normals (so the divergence
                // theorem gives a POSITIVE enclosed volume), so we reverse the
                // winding by swapping the last two indices of every triangle.
                const int* tri = triTable[cubeIndex];
                for (int t = 0; tri[t] != -1; t += 3) {
                    mesh.triangles.push_back({edgeVerts[tri[t]],
                                              edgeVerts[tri[t + 2]],
                                              edgeVerts[tri[t + 1]]});
                }
            }
        }
    }

    return mesh;
}

Mesh IsoMesher::marchCubic(const Sdf& sdf, const Vec3& min, const Vec3& max,
                           int n, double isovalue) {
    GridSpec g;
    g.min = min;
    g.max = max;
    g.nx = g.ny = g.nz = n;
    return march(sdf, g, isovalue);
}

