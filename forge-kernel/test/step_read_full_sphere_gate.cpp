struct Fx {
    const char* name;
    const char* text;
    double vol;          // closed form
    double curvedArea;   // closed form, non-planar faces only
    double volTol;
    const char* knownVol;   // non-null: the volume row is a KNOWN defect (ledger id)
};

int g_pass = 0, g_fail = 0;
void ck(bool ok, const char* fx, const char* row, const char* fmt, double a, double b, double c) {
    if (ok) ++g_pass; else ++g_fail;
    char buf[256];
    std::snprintf(buf, sizeof buf, fmt, a, b, c);
    std::printf("  [%s] %-18s %-5s %s\n", ok ? "PASS" : "FAIL", fx, row, buf);
}

void run(const Fx& f) {
    const ForeignReadResult fr = readForeignStep(f.text);
    const bool readOk = fr.ok && fr.solid && fr.closed && fr.unsupported.empty();
    ck(readOk, f.name, "read", "ok=%g closed=%g unsupported=%g", fr.ok ? 1.0 : 0.0,
       fr.closed ? 1.0 : 0.0, (double)fr.unsupported.size());
    if (!readOk) return;
    const MassProps mp = massProperties(*fr.solid);
    const double rv = std::fabs(mp.volume - f.vol) / f.vol;
    if (f.knownVol) {
        std::printf("  [KNOWN %s] %-12s vol   native %.9f closed %.9f rel %.3e (not this gate's claim)\n",
                    f.knownVol, f.name, mp.volume, f.vol, rv);
    } else {
        ck(rv <= f.volTol, f.name, "vol", "native %.9f closed %.9f rel %.3e", mp.volume, f.vol, rv);
    }
    double curved = 0.0;
    int nCurved = 0;
    for (Shell* sh : fr.solid->shells)
        for (Face* face : sh->faces) {
            if (!face || !face->surface || face->surface->kind == SurfaceKind::Plane) continue;
            Shell one; one.faces.push_back(face);
            Solid s1; s1.shells.push_back(&one);
            curved += massProperties(s1).area;
            ++nCurved;
        }
    const double ra = std::fabs(curved - f.curvedArea) / f.curvedArea;
    ck(nCurved > 0 && ra <= 1e-9, f.name, "area", "curved faces %.9f closed %.9f rel %.3e",
       curved, f.curvedArea, ra);
}

