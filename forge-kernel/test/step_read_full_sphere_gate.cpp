// test/step_read_full_sphere_gate.cpp — T-273.
//
// readForeignStep on solids whose sphere/cone face boundary passes through a POLE
// or an APEX, read back from Forge's own route-3 export (StepWriteOcct), against
// CLOSED FORM. Every one of these came back ok=1 closed=1 unsupported=0 on base
// b609b41d, so importStep's ladder accepted the wrong number silently:
//
//     full sphere r5              vol 0             vs 523.598775598
//     lower hemisphere r4         vol 6.572162705   vs 134.041286553
//     2 rad sphere wedge          vol 53.060356580  vs 85.333333333
//     apex cone r3 h5             vol 31.761931133  vs 47.123889804
//     capsule (cyl + hemisphere)  vol 46.076718092  vs 79.587013891
//     box with spherical pocket   vol 601.604253302 vs 567.275076525
//
// TWO ROOT CAUSES, each pinned by its own mutant in run_step_read_full_sphere_gate.sh:
//  (1) the (u,v) region polygon held ONE point at a pole/apex, so it could neither
//      draw the degenerate pole row nor put the seam's second traversal a turn
//      away (buildPoleAwareRegion);
//  (2) the native sphere's colatitude parameter normal S_u x S_v points INWARD, and
//      the reader set reversed = !same_sense as for every other quadric — hidden on
//      a lone sphere only because MassProps flips a wholly negative volume.
//
// The fixtures are the literal route-3 texts (frozen here so this gate does not
// depend on the writer T-159 retires). Rows per fixture:
//   [read]   ok=1 closed=1 unsupported=0
//   [vol]    massProperties volume vs closed form (relative). 1e-9, except the two
//            FULL spheres at 1e-7: MassProps integrates a regionUV v-interval with ONE
//            8-node Gauss rule, whose error on sin^3 over [0,pi] is 2.842e-08 —
//            exactly what both spheres read (filed T-345; a hemisphere's [0,pi/2]
//            is 3.9e-13).
//   [area]   area of the CURVED faces only (each face integrated alone; area does not
//            depend on orientation) vs closed form, 1e-9 — the region polygon itself.
// KNOWN rows (named ledger id) are printed with their measured error, not counted.
// NO NODE, NO OCCT in this file: links libforge_kernel_core only. Exit 0 iff green.

