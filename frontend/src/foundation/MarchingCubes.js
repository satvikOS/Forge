/**
 * Extract iso-surface from a regular grid scalar field.
 *
 * @param {object} args
 * @param {Float32Array|Float64Array} args.values - flat array length nx·ny·nz
 *                                                    indexed (z, y, x)
 * @param {number} args.nx, args.ny, args.nz - grid vertex counts
 * @param {number[]} args.origin - [x0, y0, z0]
 * @param {number[]} args.cellSize - [dx, dy, dz]
 * @param {number} args.threshold - iso-value (default 0.5)
 * @returns {{ vertProperties: Float32Array, triVerts: Uint32Array }}
 *           manifold-3d-compatible Mesh data
 */
export function extractIsoSurface({ values, nx, ny, nz, origin, cellSize, threshold = 0.5 }) {
  const [x0, y0, z0] = origin;
  const [dx, dy, dz] = cellSize;
  const idx = (i, j, k) => k * (nx * ny) + j * nx + i;
  const positions = [];
  const triangles = [];
  const vertexCache = new Map();   // edge-key → vertex index in `positions`

  // Precompute corner classifications for fast cube indexing
  for (let k = 0; k < nz - 1; k++) {
    for (let j = 0; j < ny - 1; j++) {
      for (let i = 0; i < nx - 1; i++) {
        const corners = [
          values[idx(i,     j,     k    )],
          values[idx(i + 1, j,     k    )],
          values[idx(i + 1, j + 1, k    )],
          values[idx(i,     j + 1, k    )],
          values[idx(i,     j,     k + 1)],
          values[idx(i + 1, j,     k + 1)],
          values[idx(i + 1, j + 1, k + 1)],
          values[idx(i,     j + 1, k + 1)],
        ];
        let cubeIndex = 0;
        for (let c = 0; c < 8; c++) if (corners[c] >= threshold) cubeIndex |= (1 << c);
        const edges = EDGE_TABLE[cubeIndex];
        if (edges === 0) continue;

        // Compute (or fetch cached) vertex position for each crossed edge
        const edgeVerts = new Array(12);
        for (let e = 0; e < 12; e++) {
          if (!(edges & (1 << e))) continue;
          const [ca, cb] = EDGE_VERTS[e];
          const offA = CORNER_OFFSETS[ca], offB = CORNER_OFFSETS[cb];
          // Build a unique key for this edge (across all neighbouring cells
          // that share it) so vertices are deduplicated.
          const ax = i + offA[0], ay = j + offA[1], az = k + offA[2];
          const bx = i + offB[0], by = j + offB[1], bz = k + offB[2];
          const keyA = ax + ay * nx + az * nx * ny;
          const keyB = bx + by * nx + bz * nx * ny;
          const key = keyA < keyB ? `${keyA}:${keyB}` : `${keyB}:${keyA}`;
          let vIdx = vertexCache.get(key);
          if (vIdx === undefined) {
            const va = corners[ca], vb = corners[cb];
            const t = Math.abs(vb - va) > 1e-12 ? (threshold - va) / (vb - va) : 0.5;
            const px = x0 + (ax + (bx - ax) * t) * dx;
            const py = y0 + (ay + (by - ay) * t) * dy;
            const pz = z0 + (az + (bz - az) * t) * dz;
            vIdx = positions.length / 3;
            positions.push(px, py, pz);
            vertexCache.set(key, vIdx);
          }
          edgeVerts[e] = vIdx;
        }

        // Read triangle list from TRI_TABLE
        const baseRow = cubeIndex * 16;
        for (let t = 0; t < 16; t += 3) {
          const e0 = TRI_TABLE[baseRow + t];
          if (e0 === -1) break;
          triangles.push(edgeVerts[e0], edgeVerts[TRI_TABLE[baseRow + t + 1]], edgeVerts[TRI_TABLE[baseRow + t + 2]]);
        }
      }
    }
  }
  return {
    vertProperties: new Float32Array(positions),
    triVerts: new Uint32Array(triangles),
    numProp: 3,
  };
}

/**
 * Write a binary STL directly from extracted iso-surface mesh data.
 * Bypasses manifold-3d so works even when the iso-surface is not
 * strictly manifold (slicers accept these with a warning).
 */
export function isoSurfaceToBinarySTL(meshData) {
  const positions = meshData.vertProperties;
  const tris = meshData.triVerts;
  const numTri = tris.length / 3;
  const buf = new ArrayBuffer(80 + 4 + numTri * 50);
  const view = new DataView(buf);
  const u8 = new Uint8Array(buf);
  const banner = 'ArchDisc-isosurface-STL';
  for (let i = 0; i < banner.length && i < 80; i++) u8[i] = banner.charCodeAt(i);
  view.setUint32(80, numTri, true);
  let off = 84;
  for (let t = 0; t < numTri; t++) {
    const i0 = tris[t * 3], i1 = tris[t * 3 + 1], i2 = tris[t * 3 + 2];
    const p0 = [positions[i0 * 3], positions[i0 * 3 + 1], positions[i0 * 3 + 2]];
    const p1 = [positions[i1 * 3], positions[i1 * 3 + 1], positions[i1 * 3 + 2]];
    const p2 = [positions[i2 * 3], positions[i2 * 3 + 1], positions[i2 * 3 + 2]];
    const ux = p1[0] - p0[0], uy = p1[1] - p0[1], uz = p1[2] - p0[2];
    const vx = p2[0] - p0[0], vy = p2[1] - p0[1], vz = p2[2] - p0[2];
    let nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
    const nl = Math.hypot(nx, ny, nz) || 1;
    nx /= nl; ny /= nl; nz /= nl;
    view.setFloat32(off, nx, true); off += 4;
    view.setFloat32(off, ny, true); off += 4;
    view.setFloat32(off, nz, true); off += 4;
    for (const v of [p0, p1, p2]) {
      view.setFloat32(off, v[0], true); off += 4;
      view.setFloat32(off, v[1], true); off += 4;
      view.setFloat32(off, v[2], true); off += 4;
    }
    view.setUint16(off, 0, true); off += 2;
  }
  return u8;
}

/**
 * Smooth a per-vertex scalar field (3D regular grid) with a 3×3×3
 * box kernel. Run multiple passes for stronger smoothing. Used to
 * regularize SIMP density before marching cubes so the iso-surface
 * is more likely to be manifold.
 */
export function smoothGridField(values, nx, ny, nz, passes = 1) {
  let cur = new Float32Array(values);
  let next = new Float32Array(cur.length);
  const idx = (i, j, k) => k * (nx * ny) + j * nx + i;
  for (let p = 0; p < passes; p++) {
    for (let k = 0; k < nz; k++) {
      for (let j = 0; j < ny; j++) {
        for (let i = 0; i < nx; i++) {
          let s = 0, c = 0;
          for (let dk = -1; dk <= 1; dk++) {
            const kk = k + dk; if (kk < 0 || kk >= nz) continue;
            for (let dj = -1; dj <= 1; dj++) {
              const jj = j + dj; if (jj < 0 || jj >= ny) continue;
              for (let di = -1; di <= 1; di++) {
                const ii = i + di; if (ii < 0 || ii >= nx) continue;
                s += cur[idx(ii, jj, kk)]; c++;
              }
            }
          }
          next[idx(i, j, k)] = s / c;
        }
      }
    }
    [cur, next] = [next, cur];
  }
  return cur;
}

/**
 * Convert an extracted mesh to a manifold-3d Manifold.
 * @param {object} mesh - extractIsoSurface output
 * @returns {Promise<Manifold>}
 */
export async function meshToManifold(meshData) {
  const { getManifold } = await import('./manifoldKernel.js');
  const { Manifold, Mesh } = await getManifold();
  const m = new Mesh({
    numProp: 3,
    vertProperties: meshData.vertProperties,
    triVerts: meshData.triVerts,
  });
  return new Manifold(m);
}
