/**
 * ArchDisc Foundation — Marching Cubes iso-surface extraction.
 *
 * Given a regular 3D scalar field (values on grid vertices), produce a
 * triangle mesh approximating the iso-surface at a chosen threshold.
 *
 * Used to convert SIMP topology-optimization density fields back into a
 * watertight manifold solid that we can export to STL / STEP / drawings.
 *
 * Algorithm (Lorensen & Cline 1987):
 *   1. For each cube cell of the grid, classify each of its 8 corners
 *      as inside (value ≥ threshold) or outside.
 *   2. Index into a precomputed table EDGE_TABLE[256] of which of the 12
 *      cube edges the iso-surface crosses.
 *   3. For each crossed edge, linearly interpolate to find the
 *      iso-surface vertex.
 *   4. Use TRI_TABLE[256] to look up which triangles to emit per cube
 *      configuration. Emit them with shared vertices via a vertex pool.
 *
 * The output is suitable as input to manifold-3d's `Manifold` constructor.
 * Note that this raw output may have non-manifold edges at coplanar
 * regions; for production we either smooth the field first or post-
 * process. For our 35%-volume topology-opt outputs the iso-surface is
 * generally clean.
 */

